void FpsCounter() {
    const ImGuiViewport* viewport = ImGui::GetMainViewport();
    const float pad = 12.0f * base_scale;
    ImGui::SetNextWindowPos(ImVec2(viewport->WorkPos.x + viewport->WorkSize.x - pad,
                                   viewport->WorkPos.y + pad),
                            ImGuiCond_Always, ImVec2(1.0f, 0.0f));
    ImGui::SetNextWindowBgAlpha(0.5f);
    ImGui::Begin("##fps", nullptr,
                 ImGuiWindowFlags_NoDecoration | ImGuiWindowFlags_AlwaysAutoResize |
                     ImGuiWindowFlags_NoInputs | ImGuiWindowFlags_NoNav |
                     ImGuiWindowFlags_NoFocusOnAppearing);
    const auto& s = BbSettings::Get();
    const char* upscaler = s.upscaler == BbSettings::UpscalerFsr3     ? "FSR 3.1"
                           : s.upscaler == BbSettings::UpscalerFsr4   ? "FSR 4"
                           : s.upscaler == BbSettings::UpscalerFsr411 ? "FSR 4.1.1"
                           : s.upscaler == BbSettings::UpscalerTaa    ? "TAA"
                           : s.upscaler == BbSettings::UpscalerDlss   ? "DLSS"
                                                                      : "";
    // Driveclub: the upscaler only counts while it really replaces the TAA resolve (scenes with
    // a resolve it does not know, menus and movies show the game's own).
    static const bool dc_mode = [] {
        const char* env = std::getenv("BB_DC_UPSCALE");
        return env && env[0] == '1';
    }();
    if (dc_mode && s.upscaler != BbSettings::UpscalerOff) {
        static u64 last_count;
        static std::chrono::steady_clock::time_point last_change{};
        const u64 count = BbStats::dc_upscaled_frames.load(std::memory_order_relaxed);
        const auto now = std::chrono::steady_clock::now();
        if (count != last_count) {
            last_count = count;
            last_change = now;
        }
        if (now - last_change > std::chrono::milliseconds(500)) {
            upscaler = "TAA";
        }
    }
    const float fps = frame_ms_avg > 0.0f ? 1000.0f / frame_ms_avg : 0.0f;
    if (Generating() && base_ms_avg > 0.0f) {
        // Shown frames, the game's own (base) frames, and the base frame time.
        ImGui::Text("%.0f FPS (%.0f base)  %.1f ms  %s + FG", fps, 1000.0f / base_ms_avg,
                    base_ms_avg, upscaler);
    } else {
        ImGui::Text("%.0f FPS  %.1f ms  %s", fps, frame_ms_avg, upscaler);
    }
    ImGui::End();
}

